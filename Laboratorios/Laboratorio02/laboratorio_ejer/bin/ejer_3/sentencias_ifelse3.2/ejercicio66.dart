//66. Verifica si un número es par o impar.
void ejercicio66 (){
  int numero = 32;
  if (numero % 2 == 0){
    print ("El número $numero es par");
  } else{
    print ("El número $numero es impar");
  }
}

/*Declaramos numero en un int, evaluamos con el if si numero es divisible
entre 2, en caso de ser hasi se imprime que si es par si no pasa a el else 
el cual nos imprime que es impar.*/
