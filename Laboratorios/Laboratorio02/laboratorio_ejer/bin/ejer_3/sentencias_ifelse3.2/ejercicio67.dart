//67. Verifica si un estudiante aprobó o reprobó.
void ejercicio67 (){
  int nota = 75;
  if (nota >= 60){
    print ("El estudiante aprobó con una nota de $nota");
  } else {
    print ("El estudiante reprobó cun una nota de $nota");
  }
}
