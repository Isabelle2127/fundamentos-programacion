//69. Verifica si un número es positivo o negativo.
void ejercicio69 (){
  int numero = 32;
  if (numero >= 0) {
    print("El número $numero es positivo");
  } else {
    print ("El número $numero es negativo");
  }
}

/*Declaramos numero con un int y le asignamos un valor, usamos if para ver
si numero es mayor o igual a 0, en caso de que si cumpla se imprime que si es 
positivo de caso contrario entra a else y imprime que es negativo.*/
